import React, { useState } from 'react';
import {
  Box,
  Tabs,
  Tab,
  TextField,
  Typography,
  Button,
  Modal,
  IconButton,
  InputAdornment,
  Select,
  InputLabel,
  MenuItem,
  FormControl,
} from '@mui/material';
import BackgroundTab from './BackgroundTab';
import CharacterTab from './CharacterTab';
import SpecialEffectsTab from './SpecialEffectsTab';
import ClearIcon from '@mui/icons-material/Clear';
import {
  generatePrompt,
  PromptGeneratorVariant,
  PromptValues,
} from '../../utils/prompt';

const ArtTab = () => {
  const [subTabId, setSubTabId] = useState(0);
  const [isEditMode, setIsEditMode] = useState(false); // State for edit mode
  const [manualPrompt, setManualPrompt] = useState(''); // State for manually edited prompt
  const [hasManualPrompt, setHasManualPrompt] = useState(false);
  const [promptGenerator, setPromptGenerator] =
    useState<PromptGeneratorVariant>('open');

  const [promptValues, setPromptValues] = useState<PromptValues>({
    backgroundDescription: '',
    backgroundType: '',
    characterName: '',
    race: '',
    gender: '',
    age: '',
    who: '',
    charactertype: '',
    appearance: '',
    tool: '',
    inherited_tool: false,
    action: '',
    effect: '',
    sideCharacterName: '',
    sideCharacterAppearance: '',
    sideCharacterType: '',
    sideCharacter2Name: '',
    sideCharacter2Appearance: '',
    sideCharacter2Type: '',
  });

  const updatePromptValues = (newValues: Partial<typeof promptValues>) => {
    setPromptValues(prevValues => ({ ...prevValues, ...newValues }));
  };

  // Modal State and Functions
  const [openStyleModal, setOpenStyleModal] = useState(false);

  const handleOpenStyleModal = () => setOpenStyleModal(true);
  const handleCloseStyleModal = () => setOpenStyleModal(false);

  const handleSubTabChange = (
    _event: React.SyntheticEvent,
    newTabId: number
  ) => {
    setSubTabId(newTabId);
  };

  // Constructs the prompt
  const autoGeneratedPrompt = generatePrompt({
    values: promptValues,
    variant: promptGenerator,
  });

  // The current prompt to display (either auto-generated or manually edited)
  const promptText =
    isEditMode && hasManualPrompt ? manualPrompt : autoGeneratedPrompt;

  // Toggle edit mode
  const toggleEditMode = () => {
    if (!isEditMode) {
      if (!hasManualPrompt) {
        setManualPrompt(autoGeneratedPrompt);
        setHasManualPrompt(true);
      }
    }
    setIsEditMode(!isEditMode);
  };

  return (
    <Box>
      <Tabs
        value={subTabId}
        onChange={handleSubTabChange}
        aria-label="art sub-tabs"
        sx={{ marginBottom: '1rem' }}
      >
        <Tab label="Background" />
        <Tab label="Character" />
        <Tab label="Special Effects" />
      </Tabs>

      {/* Display the relevant sub-tab */}
      <Box sx={{ display: subTabId === 0 ? 'block' : 'none' }}>
        <BackgroundTab updatePromptValues={updatePromptValues} />
      </Box>
      <Box sx={{ display: subTabId === 1 ? 'block' : 'none' }}>
        <CharacterTab updatePromptValues={updatePromptValues} />
      </Box>
      <Box sx={{ display: subTabId === 2 ? 'block' : 'none' }}>
        <SpecialEffectsTab updatePromptValues={updatePromptValues} />
      </Box>

      {/* Style Modal Button */}
      <Button
        variant="contained"
        onClick={handleOpenStyleModal}
        sx={{ marginTop: 2 }}
      >
        Add New Style
      </Button>

      {/* Modal for Styles */}
      <Modal open={openStyleModal} onClose={handleCloseStyleModal}>
        <Box
          sx={{
            padding: 4,
            backgroundColor: 'white',
            margin: 'auto',
            maxWidth: '500px',
          }}
        >
          <Typography variant="h6">Create or Edit Style</Typography>
          {/* Additional form fields for Style creation to be implemented later */}
          <Button onClick={handleCloseStyleModal}>Close</Button>
        </Box>
      </Modal>

      {/* Edit Mode Toggle Button */}
      <Box
        sx={{
          marginTop: '1.5rem',
          marginBottom: '1rem',
          display: 'flex',
          justifyContent: 'space-between',
        }}
      >
        <Typography variant="h6">Current Prompt</Typography>
        <Button
          onClick={toggleEditMode}
          variant="contained"
          color={isEditMode ? 'error' : 'primary'}
        >
          {isEditMode ? 'Edit Mode' : 'Auto generated'}
        </Button>
      </Box>

      <Box
        style={{
          marginBottom: '1rem',
        }}
      >
        <FormControl fullWidth>
          <InputLabel id="generator-variant">Generator</InputLabel>
          <Select
            labelId="generator-variant"
            value={promptGenerator}
            label="Generator"
            onChange={e => {
              console.log(e.target.value);
              setPromptGenerator(
                (e.target.value as PromptGeneratorVariant) ?? 'open'
              );
            }}
          >
            <MenuItem value="open">Open</MenuItem>
            <MenuItem value="property-list">Property list</MenuItem>
          </Select>
        </FormControl>
      </Box>

      {/* Prompt Display Box */}
      <TextField
        fullWidth
        variant="outlined"
        multiline
        minRows={4}
        value={promptText}
        placeholder="Your prompt will appear here"
        InputProps={{
          readOnly: !isEditMode,
          endAdornment: isEditMode && (
            <InputAdornment position="end">
              <IconButton onClick={() => setManualPrompt(autoGeneratedPrompt)}>
                <ClearIcon />
              </IconButton>
            </InputAdornment>
          ),
        }}
        onChange={isEditMode ? e => setManualPrompt(e.target.value) : undefined}
      />

      <Box
        sx={{
          marginTop: '1rem',
          marginBottom: '1rem',
          display: 'flex',
          gap: 2,
        }}
      >
        <Button variant="contained">Generate</Button>
        <Button variant="outlined" color="warning">
          Return
        </Button>
        <Button variant="outlined" color="error">
          Reset
        </Button>
      </Box>
    </Box>
  );
};

export default ArtTab;
