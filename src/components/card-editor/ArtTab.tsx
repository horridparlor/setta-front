import React, { useState } from 'react';
import { Box, Tabs, Tab, TextField, Typography, Button } from '@mui/material';
import BackgroundTab from './BackgroundTab'; 
import CharacterTab from './CharacterTab';    
import SpecialEffectsTab from './SpecialEffectsTab'; 

const ArtTab = () => {
  const [subTabId, setSubTabId] = useState(0);
  const [isEditMode, setIsEditMode] = useState(false); // State for edit mode
  const [manualPrompt, setManualPrompt] = useState(''); // State for manually edited prompt
  const [hasManualPrompt, setHasManualPrompt] = useState(false);
  const BACKGROUND_TAB = 0;
  const CHARACTER_TAB = 1;
  const SPECIAL_EFFECTS_TAB = 2;

  const handleSubTabChange = (_event: React.SyntheticEvent, newTabId: number) => {
    setSubTabId(newTabId);
  };

  const [promptValues, setPromptValues] = useState({
    backgroundDescription: '',
    backgroundType: '',
    characterName: '',
    race: '',
    gender: '',
    age: '',
    Charactertype: '',
    appearance: '',
    tool: '',
    action: '',
    effect: ''
  });

  const updatePromptValues = (newValues: Partial<typeof promptValues>) => {
    setPromptValues(prevValues => ({ ...prevValues, ...newValues }));
  };

  // Constructs the prompt
  const autoGeneratedPrompt = `Background: ${promptValues.backgroundDescription || 'N/A'}
  Type: ${promptValues.backgroundType || 'N/A'}
  Character: ${promptValues.characterName || 'N/A'}
  Race: ${promptValues.race || 'N/A'}
  Gender: ${promptValues.gender || 'N/A'}
  Age: ${promptValues.age || 'N/A'}
  Character type: ${promptValues.Charactertype || 'N/A'}
  Appearance: ${promptValues.appearance || 'N/A'}
  Tool: ${promptValues.tool || 'N/A'}
  Action: ${promptValues.action || 'N/A'}
  Effect: ${promptValues.effect || 'N/A'}`;

  // The current prompt to display (either auto-generated or manually edited)
  const promptText = isEditMode && hasManualPrompt ? manualPrompt : autoGeneratedPrompt;

  // Toggle edit mode
  const toggleEditMode = () => {
    if (!isEditMode) {
      // When entering edit mode for the first time, copy the auto-generated prompt into manualPrompt.
      if (!hasManualPrompt) {
        setManualPrompt(autoGeneratedPrompt);
        setHasManualPrompt(true); // Mark that a manual prompt is being used
      }
    }
    setIsEditMode(!isEditMode);
  };
  return (
    <Box>
      <Tabs
        value={subTabId}
        onChange={handleSubTabChange}
        aria-label="art sub-tabs"
        sx={{ marginBottom: '1rem' }}
      >
        <Tab label="Background" />
        <Tab label="Character" />
        <Tab label="Special Effects" />
      </Tabs>

      {/* Display the relevant sub-tab */}
      <Box sx={{ display: subTabId === BACKGROUND_TAB ? 'block' : 'none' }}>
        <BackgroundTab updatePromptValues={updatePromptValues} />
      </Box>
      <Box sx={{ display: subTabId === CHARACTER_TAB ? 'block' : 'none' }}>
        <CharacterTab updatePromptValues={updatePromptValues} />
      </Box>
      <Box sx={{ display: subTabId === SPECIAL_EFFECTS_TAB ? 'block' : 'none' }}>
        <SpecialEffectsTab updatePromptValues={updatePromptValues} />
      </Box>

      {/* Edit Mode Toggle Button */}
      <Box sx={{ marginTop: '1.5rem', marginBottom: '1rem', display: 'flex', justifyContent: 'space-between' }}>
        <Typography variant="h6">Current Prompt</Typography>
        <Button onClick={toggleEditMode} variant="contained" color={isEditMode ? 'error' : 'primary'}>
          {isEditMode ? 'Edit Mode' : 'Auto generated'}
        </Button>
      </Box>

      {/* Prompt Display Box */}
      <TextField
        fullWidth
        variant="outlined"
        multiline
        minRows={4}
        value={promptText}
        placeholder="Your prompt will appear here"
        InputProps={{
          readOnly: !isEditMode,  // Only editable when in Edit Mode
        }}
        onChange={isEditMode ? (e) => setManualPrompt(e.target.value) : undefined} // Only allow edits in Edit Mode
      />
    </Box>
  );
};

export default ArtTab;
